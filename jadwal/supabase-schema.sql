create or replace function public.pkkm_admin_list(p_admin_key text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare out jsonb; expected text;
begin
 select password_sha256 into expected from public.pkkm_admin_config where singleton=true;
 if expected is null or encode(extensions.digest(convert_to(coalesce(p_admin_key,''),'UTF8'),'sha256'),'hex') <> expected then raise exception 'unauthorized' using errcode='42501'; end if;
 select coalesce(jsonb_agg(jsonb_build_object('id',id,'NO.',no,'Nama Madrasah',nama_madrasah,'Nama Kepala Madrasah',nama_kepala,'Tanggal PKKM',tanggal,'Jam',jam,'Lokasi',lokasi,'Catatan',catatan,'share_id',share_id) order by no),'[]'::jsonb) into out from public.pkkm_schedules;
 return out;
end $$;
