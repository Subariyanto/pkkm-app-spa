-- pengaman: cek kata sandi admin
create or replace function public.pkkm_pw_ok(p_admin_key text)
returns boolean language plpgsql security definer set search_path='' as $$
declare expected text;
begin
  select password_sha256 into expected from public.pkkm_admin_config where singleton=true;
  return expected is not null
     and encode(extensions.digest(convert_to(coalesce(p_admin_key,''),'UTF8'),'sha256'),'hex') = expected;
end $$;
revoke all on function public.pkkm_pw_ok(text) from public;

create or replace function public.pkkm_assert_pw(p_admin_key text)
returns void language plpgsql security definer set search_path='' as $$
begin
  if not public.pkkm_pw_ok(p_admin_key) then
    raise exception 'unauthorized' using errcode='42501';
  end if;
end $$;
revoke all on function public.pkkm_assert_pw(text) from public;

-- daftar jadwal untuk admin
create or replace function public.pkkm_admin_list(p_admin_key text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare out jsonb;
begin
  perform public.pkkm_assert_pw(p_admin_key);
  select coalesce(jsonb_agg(jsonb_build_object(
    'id',id,'NO.',no,'Nama Madrasah',nama_madrasah,'Nama Kepala Madrasah',nama_kepala,
    'Tanggal PKKM',tanggal,'Jam',jam,'Lokasi',lokasi,'Catatan',catatan,'share_id',share_id) order by no),'[]'::jsonb)
  into out from public.pkkm_schedules;
  return out;
end $$;

-- simpan (tambah/ubah) termasuk nama kepala madrasah
create or replace function public.pkkm_admin_save_v3(
  p_admin_key text, p_id bigint, p_nama_madrasah text, p_nama_kepala text,
  p_tanggal date, p_jam text, p_lokasi text, p_catatan text)
returns bigint language plpgsql security definer set search_path='' as $$
declare new_id bigint; next_no integer; nm text; kp text;
begin
  perform public.pkkm_assert_pw(p_admin_key);
  nm := nullif(trim(coalesce(p_nama_madrasah,'')),'');
  kp := nullif(trim(coalesce(p_nama_kepala,'')),'');
  if nm is null then raise exception 'nama madrasah wajib diisi' using errcode='22023'; end if;
  if kp is null then raise exception 'nama kepala madrasah wajib diisi' using errcode='22023'; end if;

  if p_id is null then
    select coalesce(max(no),0)+1 into next_no from public.pkkm_schedules;
    insert into public.pkkm_schedules(no,nama_madrasah,nama_kepala,tanggal,jam,lokasi,catatan)
    values(next_no,nm,kp,p_tanggal,coalesce(p_jam,''),coalesce(p_lokasi,''),coalesce(p_catatan,''))
    returning id into new_id;
  else
    update public.pkkm_schedules
       set nama_madrasah=nm, nama_kepala=kp, tanggal=p_tanggal,
           jam=coalesce(p_jam,''), lokasi=coalesce(p_lokasi,''),
           catatan=coalesce(p_catatan,''), updated_at=now()
     where id=p_id returning id into new_id;
    if new_id is null then raise exception 'jadwal tidak ditemukan' using errcode='P0002'; end if;
  end if;
  return new_id;
end $$;

-- kompatibilitas: RPC lama (tanpa nama kepala)
create or replace function public.pkkm_admin_update_v2(
  p_admin_key text, p_id bigint, p_nama_madrasah text,
  p_tanggal date, p_jam text, p_lokasi text, p_catatan text)
returns boolean language plpgsql security definer set search_path='' as $$
begin
  perform public.pkkm_assert_pw(p_admin_key);
  update public.pkkm_schedules
     set nama_madrasah=coalesce(nullif(trim(p_nama_madrasah),''),nama_madrasah),
         tanggal=p_tanggal, jam=coalesce(p_jam,''), lokasi=coalesce(p_lokasi,''),
         catatan=coalesce(p_catatan,''), updated_at=now()
   where id=p_id;
  return found;
end $$;

create or replace function public.pkkm_admin_update(
