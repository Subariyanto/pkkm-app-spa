-- PKKM Jadwal — pindah backend ke Supabase self-hosted VPS (api.pokjawasjember.com)
-- Jalankan sekali di supabase-db. Aman diulang (idempotent).
-- Skema RPC dibuat identik dengan versi Supabase cloud agar frontend tidak perlu diubah.

create extension if not exists pgcrypto with schema extensions;

create table if not exists public.pkkm_schedules (
  id bigint generated by default as identity primary key,
  no integer not null unique,
  nama_madrasah text not null,
  nama_kepala text not null,
  tanggal date,
  jam text not null default '',
  lokasi text not null default '',
  catatan text not null default '',
  share_id text not null unique default encode(extensions.gen_random_bytes(24),'hex'),
  updated_at timestamptz not null default now()
);

create table if not exists public.pkkm_admin_config (
  singleton boolean primary key default true check(singleton),
  password_sha256 text not null
);

create table if not exists public.pkkm_evaluators (
  slot smallint primary key check (slot in (1,2)),
  image_data text not null,
  updated_at timestamptz not null default now()
);

