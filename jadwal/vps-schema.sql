  return found;
end $$;

-- hapus jadwal
create or replace function public.pkkm_admin_delete_v1(p_admin_key text, p_id bigint)
returns boolean language plpgsql security definer set search_path='' as $$
begin
  perform public.pkkm_assert_pw(p_admin_key);
  delete from public.pkkm_schedules where id=p_id;
  return found;
end $$;

-- halaman publik per madrasah (via share_id)
create or replace function public.pkkm_public_schedule(p_share_id text)
returns jsonb language sql stable security definer set search_path='' as $$
 select jsonb_build_object('NO.',no,'Nama Madrasah',nama_madrasah,'Nama Kepala Madrasah',nama_kepala,
   'Tanggal PKKM',tanggal,'Jam',jam,'Lokasi',lokasi,'Catatan',catatan)
 from public.pkkm_schedules where share_id=p_share_id;
$$;

-- daftar publik semua madrasah (tanpa share_id)
create or replace function public.pkkm_public_schedules()
returns jsonb language sql stable security definer set search_path='' as $$
 select coalesce(jsonb_agg(jsonb_build_object('NO.',no,'Nama Madrasah',nama_madrasah,
   'Nama Kepala Madrasah',nama_kepala,'Tanggal PKKM',tanggal,'Jam',jam,
   'Lokasi',lokasi,'Catatan',catatan) order by no),'[]'::jsonb)
 from public.pkkm_schedules;
$$;

-- foto tim penilai
create or replace function public.pkkm_public_evaluators()
returns jsonb language sql stable security definer set search_path='' as $$
 select coalesce(jsonb_agg(jsonb_build_object('slot',slot,'image_data',image_data) order by slot),'[]'::jsonb)
 from public.pkkm_evaluators;
$$;

create or replace function public.pkkm_admin_save_evaluator(p_admin_key text, p_slot smallint, p_image_data text)
returns boolean language plpgsql security definer set search_path='' as $$
begin
  perform public.pkkm_assert_pw(p_admin_key);
  if p_slot not in (1,2) then raise exception 'slot tidak valid' using errcode='22023'; end if;
  insert into public.pkkm_evaluators(slot,image_data,updated_at) values(p_slot,p_image_data,now())
  on conflict(slot) do update set image_data=excluded.image_data, updated_at=now();
  return true;
end $$;

