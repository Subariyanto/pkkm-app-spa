-- PKKM Jadwal v4 — sesi (jam) berisi banyak madrasah + "ditempatkan di"
-- Idempotent. Jalankan: docker exec -i supabase-db psql -U postgres < vps-schema-v4-sesi.sql

-- ---------- tabel sesi ----------
create table if not exists public.pkkm_sessions (
  id bigint generated by default as identity primary key,
  tanggal date,
  jam text not null default '',
  nama_tempat text not null default '',
  lokasi text not null default '',
  catatan text not null default '',
  share_id text not null unique default encode(extensions.gen_random_bytes(24),'hex'),
  updated_at timestamptz not null default now()
);

alter table public.pkkm_schedules
  add column if not exists session_id bigint references public.pkkm_sessions(id) on delete cascade;

create index if not exists pkkm_schedules_session_idx on public.pkkm_schedules(session_id);

alter table public.pkkm_sessions enable row level security;
revoke all on public.pkkm_sessions from anon, authenticated;

-- ---------- migrasi data lama: 1 sesi per (tanggal, jam) ----------
-- Tempat pelaksanaan = madrasah dengan nomor terkecil pada slot itu
insert into public.pkkm_sessions(tanggal,jam,nama_tempat,lokasi,catatan,share_id)
select tanggal,jam,nama_madrasah,lokasi,catatan,share_id
from (
  select distinct on (coalesce(tanggal::text,'_'), jam)
         tanggal,jam,nama_madrasah,lokasi,catatan,share_id,no
  from public.pkkm_schedules
  where session_id is null
  order by coalesce(tanggal::text,'_'), jam, no
) s
where not exists (
  select 1 from public.pkkm_sessions x
  where x.tanggal is not distinct from s.tanggal and x.jam = s.jam
);

update public.pkkm_schedules sc
set session_id = (
  select min(x.id) from public.pkkm_sessions x
  where x.tanggal is not distinct from sc.tanggal and x.jam = sc.jam)
where sc.session_id is null;

-- ---------- helper: hak akses (sudah ada dari v3) ----------
create or replace function public.pkkm_assert_pw(p_admin_key text)
returns void language plpgsql security definer set search_path='' as $$
begin
  if not public.pkkm_pw_ok(p_admin_key) then
    raise exception 'unauthorized' using errcode='42501';
  end if;
end $$;
revoke all on function public.pkkm_assert_pw(text) from public;

-- ---------- bentuk keluaran sesi + madrasahnya ----------
create or replace function public.pkkm_session_json(p_row public.pkkm_sessions)
returns jsonb language sql stable security definer set search_path='' as $$
 select jsonb_build_object(
   'id', p_row.id,
   'Tanggal PKKM', p_row.tanggal,
   'Jam', p_row.jam,
   'Tempat', p_row.nama_tempat,
   'Lokasi', p_row.lokasi,
   'Catatan', p_row.catatan,
   'share_id', p_row.share_id,
   'madrasah', (
     select coalesce(jsonb_agg(jsonb_build_object(
       'id', m.id, 'NO.', m.no,
       'Nama Madrasah', m.nama_madrasah,
       'Nama Kepala Madrasah', m.nama_kepala) order by m.no), '[]'::jsonb)
     from public.pkkm_schedules m where m.session_id = p_row.id)
 );
$$;
revoke all on function public.pkkm_session_json(public.pkkm_sessions) from public;

-- ---------- daftar publik & admin ----------
create or replace function public.pkkm_public_schedules()
returns jsonb language sql stable security definer set search_path='' as $$
 select coalesce(jsonb_agg(public.pkkm_session_json(s) order by s.tanggal nulls last, s.jam),'[]'::jsonb)
 from public.pkkm_sessions s;
$$;

create or replace function public.pkkm_admin_list(p_admin_key text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare out jsonb;
begin
  perform public.pkkm_assert_pw(p_admin_key);
  select coalesce(jsonb_agg(public.pkkm_session_json(s) order by s.tanggal nulls last, s.jam),'[]'::jsonb)
  into out from public.pkkm_sessions s;
  return out;
end $$;

create or replace function public.pkkm_public_schedule(p_share_id text)
returns jsonb language sql stable security definer set search_path='' as $$
 select public.pkkm_session_json(s) from public.pkkm_sessions s where s.share_id = p_share_id;
$$;

-- ---------- simpan sesi ----------
create or replace function public.pkkm_admin_session_save(
  p_admin_key text, p_id bigint, p_tanggal date, p_jam text,
  p_tempat text, p_lokasi text, p_catatan text)
returns bigint language plpgsql security definer set search_path='' as $$
declare new_id bigint;
begin
  perform public.pkkm_assert_pw(p_admin_key);
  if p_id is null then
    insert into public.pkkm_sessions(tanggal,jam,nama_tempat,lokasi,catatan)
    values (p_tanggal, coalesce(p_jam,''), coalesce(p_tempat,''), coalesce(p_lokasi,''), coalesce(p_catatan,''))
    returning id into new_id;
  else
    update public.pkkm_sessions
       set tanggal=p_tanggal, jam=coalesce(p_jam,''), nama_tempat=coalesce(p_tempat,''),
           lokasi=coalesce(p_lokasi,''), catatan=coalesce(p_catatan,''), updated_at=now()
     where id=p_id returning id into new_id;
    if new_id is null then raise exception 'sesi tidak ditemukan' using errcode='P0002'; end if;
  end if;
  return new_id;
end $$;

create or replace function public.pkkm_admin_session_delete(p_admin_key text, p_id bigint)
returns boolean language plpgsql security definer set search_path='' as $$
begin
  perform public.pkkm_assert_pw(p_admin_key);
  delete from public.pkkm_sessions where id=p_id;
  return found;
end $$;

-- ---------- simpan madrasah dalam sesi ----------
create or replace function public.pkkm_admin_madrasah_save(
  p_admin_key text, p_id bigint, p_session_id bigint,
  p_nama_madrasah text, p_nama_kepala text)
returns bigint language plpgsql security definer set search_path='' as $$
declare new_id bigint; next_no integer; nm text; kp text;
begin
  perform public.pkkm_assert_pw(p_admin_key);
  nm := nullif(trim(coalesce(p_nama_madrasah,'')),'');
  kp := nullif(trim(coalesce(p_nama_kepala,'')),'');
  if nm is null then raise exception 'nama madrasah wajib diisi' using errcode='22023'; end if;
  if kp is null then raise exception 'nama kepala madrasah wajib diisi' using errcode='22023'; end if;
  if p_session_id is null then raise exception 'sesi wajib dipilih' using errcode='22023'; end if;

  if p_id is null then
    select coalesce(max(no),0)+1 into next_no from public.pkkm_schedules;
    insert into public.pkkm_schedules(session_id,no,nama_madrasah,nama_kepala,
      tanggal,jam,lokasi,catatan)
    select p_session_id, next_no, nm, kp, s.tanggal, s.jam, s.lokasi, s.catatan
    from public.pkkm_sessions s where s.id=p_session_id
    returning id into new_id;
  else
    update public.pkkm_schedules
       set session_id=p_session_id, nama_madrasah=nm, nama_kepala=kp, updated_at=now()
     where id=p_id returning id into new_id;
    if new_id is null then raise exception 'madrasah tidak ditemukan' using errcode='P0002'; end if;
  end if;
  return new_id;
end $$;

create or replace function public.pkkm_admin_madrasah_delete(p_admin_key text, p_id bigint)
returns boolean language plpgsql security definer set search_path='' as $$
begin
  perform public.pkkm_assert_pw(p_admin_key);
  delete from public.pkkm_schedules where id=p_id;
  return found;
end $$;

-- ---------- hak eksekusi ----------
revoke all on function
  public.pkkm_public_schedules(),
  public.pkkm_admin_list(text),
  public.pkkm_public_schedule(text),
  public.pkkm_admin_session_save(text,bigint,date,text,text,text,text),
  public.pkkm_admin_session_delete(text,bigint),
  public.pkkm_admin_madrasah_save(text,bigint,bigint,text,text),
  public.pkkm_admin_madrasah_delete(text,bigint)
from public;

grant execute on function
  public.pkkm_public_schedules(),
  public.pkkm_admin_list(text),
  public.pkkm_public_schedule(text),
  public.pkkm_admin_session_save(text,bigint,date,text,text,text,text),
  public.pkkm_admin_session_delete(text,bigint),
  public.pkkm_admin_madrasah_save(text,bigint,bigint,text,text),
  public.pkkm_admin_madrasah_delete(text,bigint)
to anon, authenticated;
